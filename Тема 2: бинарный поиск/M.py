# Читаем N (количество проводов) и K (сколько нужно отрезков)
N, K = map(int, input().split())

# Читаем длины проводов
wires = []
for i in range(N):
    wires.append(int(input()))

# Находим максимальную длину провода (верхняя граница поиска)
max_len = max(wires)

# Бинарный поиск по длине отрезка
left = 1  # минимальная длина (1 см)
right = max_len  # максимальная длина
answer = 0  # здесь запоминаем лучший ответ

while left <= right:
    mid = (left + right) // 2  # угадываем длину

    # Считаем, сколько отрезков длины mid можно получить
    count = 0
    for wire in wires:
        count += wire // mid  # сколько кусков из этого провода

    # Если получили достаточно отрезков
    if count >= K:
        answer = mid  # запоминаем ответ
        left = mid + 1  # пробуем длину побольше
    else:
        right = mid - 1  # пробуем длину поменьше

# Выводим ответ
print(answer)